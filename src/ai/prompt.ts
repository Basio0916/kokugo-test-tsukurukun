// 小問の作り方と記法（大問を作る・小問を足す・会話で直すで共通）
const QUESTION_RULES = `## 問いの作り方
- 単元の指導事項を土台にして、本文の理解を確かめる問いを作る。指導事項にない記号の問いを入れるときは、理由にそのことを書く
- 知識・技能（語句の意味、表現の技法など）と、思考・判断・表現（人物の心情、表現の効果、内容の解釈など）の両方を入れる
- 同じ問い方を繰り返さない。「最も適切なものを選ぶ」「抜き出す」「記述する」だけの並びにせず、次の引き出しから本文に合うものを組み合わせる。全部を入れる必要はない
  - 否定形の選択: 当てはまらないものを一つ選ばせる
  - 答え方の条件: 「「〜。」に続くように」「「◯◯」という言葉を使って」「◯字以上◯字以内で」「登場人物の言動から」など。字数の下限と上限を示すときは、字数（charLimit）を上限にする
  - 本文の語を足場にした言葉の知識: 本文の語の熟語の構成、語句の意味、対義語など
  - 構成や叙述そのもの: 段落の役割、回想の入れ方、語り手の視点、表現の特徴など
  - 並べ替え: 順序を短答（short）で答えさせる。答えは語そのもので書く（例: 楽しむ者→好む者→知る者）。番号や記号では書かない
  - 問いどうしのつながり: 同じ箇所を続く問いで掘り下げる（語の意味を問い、次にそう言える理由を問うなど）。前の問いの答えがわからなくても答えられるようにし、問い文に「前の問い」とは書かない
  - 空欄補充: 傍線部や文章の内容を要約した一〜二文を穴埋め文（fillText）にし、空欄の場所に答えを [[答え]] と書く。「◯字以内」で答えさせるときだけ [[答え｜10]] のように字数の上限を添える。空欄は一〜四つ。本文から抜き出す空欄は extract（答えは本文のとおりに書く）、考えて答える空欄は short にする。answer と charLimit は書かない。穴埋め文は本文を写さず要約にし、答えを [[ ]] の外に書かない。問い文は「次の文の空欄に当てはまる言葉を、本文からそれぞれ抜き出しなさい。」のように書き、Ⅰ・Ⅱの番号は書かない
- ある問いの問い文や選択肢で、別の問いの答えがわかるようにしない
- 本文の外の知識（作者の背景、文学史など）は、先生の希望や頼みに授業で扱った知識として書かれているときだけ問う
- 小問は、問う箇所が本文に出てくる順に並べる（本文全体を問う問いは最後に置く。同じ箇所を掘り下げる問いは続けて並べる）
- 解答形式は、記号選択（choice）・本文からの抜き出し（extract）・記述（description）・短答（short）から選ぶ
- 記号選択の選択肢は四つを基本にする。語群から選ぶ問いなど、問いに合わせて三〜七つにしてよい。紛らわしいが本文に照らせば一つに決まるようにする。記号（ア・イ…）は付けない。正答（correctChoice）は、正しい選択肢の文を一字も変えずに書く
- 抜き出しの答えは、本文のとおりに書き、字数（charLimit）を必ず付けて答えの字数に合わせる
- 記述は字数（charLimit）と模範解答（answer）と採点の観点（rubric）を付ける。字数は二十〜六十字を基本にし、自分の考えを書かせる問いでも百字までにする
- 抜き出しと短答の答えは一つにする。解答欄が一つなので、二つ以上を答えさせたいときは問いを分けるか、空欄補充にする
- 観点（kanten）は指導事項の記号に合わせる。(1)〜(3) の記号は知識・技能（knowledge）、A〜C の記号は思考・判断・表現（thinking）にする
- 問い文は、中学校の定期テストで使う言い回しで書く（「〜とありますが、…。最も適切なものを、次の{範囲}から一つ選び、記号で答えなさい。」など）

## 傍線部と記法（必ず守る）
- 傍線を引く箇所は marks に、本文から一字も変えずにそのまま引用して書く。句読点やかぎかっこを含めるかどうかも本文のとおりにする
- 引用が本文に二回以上出てくるときは、before に直前の数文字を本文のとおりに書く
- 問い文の中では、傍線部を {傍線部:A}（紙面では「傍線部①」になる）または {番号:A}（「①」だけになる）、選択肢の範囲を {範囲}（「ア〜エ」になる）と書く
- 番号（①②、問一）や記号（ア〜エ）を文字で書かない。番号はシステムが付ける
- 配点の点数は書かず、重み（weight、1〜5 の整数）で小問どうしの重さだけを示す`

